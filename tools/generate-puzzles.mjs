// Badoku-Extreme - puzzle pool generator.
// Usage: node tools/generate-puzzles.mjs [--seed 123] [--out supabase/seed/puzzles.sql]
//
// Writes INSERT statements for public.puzzles and public.puzzle_solutions.
// The output contains SOLUTIONS and is gitignored (public repo!). Run the
// file in the Supabase SQL editor. It is idempotent: puzzles are unique by
// their givens, re-running adds nothing twice.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeRng, makePuzzleRetry, gridToString, countGivens, checkPuzzle } from './sudoku-core.mjs';

// Target counts and given ranges (CLAUDE.md section 7). Adjust after bot runs.
const PLAN = [
  { size: 9, difficulty: 'leicht', givens: [38, 42], count: 30 },
  { size: 9, difficulty: 'mittel', givens: [32, 36], count: 15 },
  { size: 6, difficulty: 'leicht', givens: [14, 16], count: 10 },
  { size: 4, difficulty: 'leicht', givens: [6, 7], count: 10 },
];

const args = process.argv.slice(2);
const argValue = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : fallback;
};
const seed = Number(argValue('--seed', Date.now() % 2147483647));
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = resolve(repoRoot, argValue('--out', 'supabase/seed/puzzles.sql'));

const rng = makeRng(seed);
const seen = new Set();
const rows = [];
const summary = [];

for (const item of PLAN) {
  const t0 = Date.now();
  let attempts = 0;
  const givensList = [];
  while (givensList.length < item.count) {
    const r = makePuzzleRetry(item.size, item.givens, rng);
    attempts += r.attempts;
    const givens = gridToString(r.puzzle);
    if (seen.has(givens)) continue;
    const problems = checkPuzzle(r.puzzle, r.solution, item.size);
    if (problems.length) throw new Error(`generated puzzle failed checks: ${problems.join(', ')}`);
    seen.add(givens);
    givensList.push(countGivens(r.puzzle));
    rows.push({ size: item.size, difficulty: item.difficulty, givens, solution: gridToString(r.solution) });
  }
  summary.push(
    `${item.size}x${item.size} ${item.difficulty}: ${item.count} puzzles, givens ${Math.min(...givensList)}-${Math.max(...givensList)}, ` +
      `${attempts} attempts, ${Date.now() - t0} ms`
  );
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
lines.push(`-- Badoku-Extreme puzzle pool. GENERATED by tools/generate-puzzles.mjs (seed ${seed}) on ${new Date().toISOString()}.`);
lines.push('-- Contains solutions. This file is gitignored and must never be committed.');
lines.push('-- Idempotent: re-running adds no duplicates (puzzles are unique by givens).');
lines.push('');
lines.push('begin;');
lines.push('');
lines.push('insert into public.puzzles (size, difficulty, givens) values');
lines.push(rows.map((r) => `  (${r.size}, ${q(r.difficulty)}, ${q(r.givens)})`).join(',\n'));
lines.push('on conflict (givens) do nothing;');
lines.push('');
lines.push('insert into public.puzzle_solutions (puzzle_id, solution)');
lines.push('select p.id, v.solution');
lines.push('from (values');
lines.push(rows.map((r) => `  (${q(r.givens)}, ${q(r.solution)})`).join(',\n'));
lines.push(') as v(givens, solution)');
lines.push('join public.puzzles p on p.givens = v.givens');
lines.push('on conflict (puzzle_id) do nothing;');
lines.push('');
lines.push('commit;');
lines.push('');
lines.push('-- Check: select size, difficulty, count(*) from public.puzzles group by 1, 2 order by 1, 2;');
lines.push('');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log(`seed ${seed}`);
for (const s of summary) console.log(s);
console.log(`${rows.length} puzzles written to ${outPath}`);
